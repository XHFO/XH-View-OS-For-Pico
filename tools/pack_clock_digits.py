#!/usr/bin/env python3
"""无损裁去时钟字形每行两端透明像素，不改字体、灰阶或采样。
Losslessly trim transparent row margins from existing clock rasters without changing fonts, grays or sampling.
"""
from pathlib import Path
import argparse
import hashlib
import re

ROOT = Path(__file__).resolve().parents[1]

def generate():
    source = ROOT / 'main/system/pico_clock_digits.h'
    text = source.read_text()
    raster = bytes(int(v, 16) for v in re.findall(r'0x([0-9a-f]{2})', text))
    assert len(raster) == 10 * 128 * 192 // 2
    offsets, margins, data = [0], [], bytearray()
    restored = bytearray()
    for at in range(0, len(raster), 64):
        row = raster[at:at+64]
        used = [i for i, v in enumerate(row) if v]
        left, right = (used[0], used[-1] + 1) if used else (0, 0)
        margins.append(left)
        data.extend(row[left:right])
        offsets.append(len(data))
        restored.extend(bytes(left) + row[left:right] + bytes(64-right))
    assert bytes(restored) == raster and len(data) < 65536
    lines = ['/* SPDX-License-Identifier: OFL-1.1',
             ' * 原始OFL时钟灰阶逐像素保留，仅去除行透明边；来源许可见pico_clock_digits.h。',
             ' * Preserve every original OFL clock gray pixel, trimming only transparent row margins; see pico_clock_digits.h.',
             ' * Generated by tools/pack_clock_digits.py; do not edit.',
             ' * Raster SHA256: ' + hashlib.sha256(raster).hexdigest(), ' */', '#pragma once', '#include <stdint.h>',
             '#define PS_CLOCK_MASK_W 128', '#define PS_CLOCK_MASK_H 192']
    for name, typ, values in [('ps_clock_row_offset', 'uint16_t', offsets), ('ps_clock_row_left', 'uint8_t', margins), ('ps_clock_row_data', 'uint8_t', data)]:
        lines.append(f'static const {typ} {name}[{len(values)}]={{')
        for at in range(0, len(values), 24):
            lines.append('    ' + ','.join(str(v) for v in values[at:at+24]) + ',')
        lines.append('};')
    return '\n'.join(lines) + '\n'

def main():
    p = argparse.ArgumentParser(description=__doc__); p.add_argument('--check', action='store_true'); args = p.parse_args()
    text = generate(); target = ROOT / 'main/system/pico_clock_digits_sparse.h'
    if args.check:
        assert target.read_text() == text, 'Regenerate sparse clock raster'
    else:
        target.write_text(text)
    print('PASS: all 245760 gray pixels preserved, no RAM decompression or font changes')

if __name__ == '__main__': main()
