"""生成有界双语文案包与键表说明。Generate the bounded bilingual catalog and key documentation."""
import argparse
import json
import re
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "main/system/pico_i18n_table.inc"
OUTPUT = ROOT / "main/system/pico_i18n_packed.inc"
DOC = ROOT / "docs/I18N_KEY_LIST.md"
ROW = re.compile(r'^PS_I18N\(("(?:[^"\\]|\\.)*"), ("(?:[^"\\]|\\.)*"), ("(?:[^"\\]|\\.)*")\)$')


def generate():
    rows = []
    for line in SOURCE.read_text().splitlines():
        if not line.startswith("PS_I18N("):
            continue
        match = ROW.fullmatch(line)
        if not match:
            raise ValueError("Invalid catalog row: " + line)
        rows.append(tuple(json.loads(field) for field in match.groups()))
    assert 0 < len(rows) < 1024 and len({row[0] for row in rows}) == len(rows)
    assert all(field and not any(c in field for c in "\x00\t\n") for row in rows for field in row)
    start = 12 + len(rows) * 6
    offsets, strings, seen = [], bytearray(), {}
    for row in rows:
        for field in row:
            if field not in seen:
                seen[field] = start + len(strings)
                strings.extend(field.encode() + b"\0")
            offsets.append(seen[field])
    raw = b"PICOTR1\0" + struct.pack("<HH", len(rows), 0)
    raw += struct.pack("<" + "H" * len(offsets), *offsets) + strings
    assert 24 <= len(raw) <= 65535
    encoder = zlib.compressobj(9, zlib.DEFLATED, -15)
    packed = b"PICO4DF1" + struct.pack("<II", len(raw), zlib.crc32(raw)) + encoder.compress(raw) + encoder.flush()
    lines = ["/* Generated by tools/pack_pico_i18n.py; do not edit. / 自动生成，请勿手改。 */",
             f"#define PS_I18N_CATALOG_COUNT {len(rows)}u", "static const uint8_t s_catalog_packed[] = {"]
    for pos in range(0, len(packed), 20):
        lines.append("    " + ",".join(f"0x{b:02x}" for b in packed[pos:pos + 20]) + ",")
    lines.append("};")
    doc = "# Interface language keys / 界面语言键\n\n"
    doc += "Generated from `main/system/pico_i18n_table.inc`; the firmware stores both languages in a lossless catalog.\n"
    doc += "从同一份文案表生成；固件保留两种语言，以无损压缩节省 APP 空间。\n\n```tsv\nkey\tzh-Hans\ten\n"
    doc += "\n".join("\t".join(row) for row in rows) + "\n```\n"
    return "\n".join(lines) + "\n", doc, len(rows), len(raw), len(packed)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    inc, doc, rows, raw, packed = generate()
    if args.check:
        assert OUTPUT.read_text() == inc, "Regenerate pico_i18n_packed.inc"
        assert DOC.read_text() == doc, "Regenerate I18N_KEY_LIST.md"
    else:
        OUTPUT.write_text(inc)
        DOC.write_text(doc)
    print(f"Bilingual catalog: {rows} keys, {raw} raw bytes, {packed} packed bytes")


if __name__ == "__main__":
    main()
