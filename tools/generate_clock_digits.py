#!/usr/bin/env python3
"""从仓库内OFL字体生成粗体时钟数字灰阶mask，避免受正文120px字号上限限制。
Generate bold clock digit masks from the bundled OFL font, independent of the 120px reader-font limit.
"""
from pathlib import Path
import argparse
import hashlib
from PIL import Image, ImageDraw, ImageFont

ROOT=Path(__file__).resolve().parents[1]
WIDTH,HEIGHT=128,192


def generate():
    source=ROOT/'sdcard/fonts/ChillDuanSansVF.ttf'
    font=ImageFont.truetype(str(source),384)
    axes=font.get_variation_axes()
    font.set_variation_by_axes([700 if axis['name']==b'Weight' else axis['default'] for axis in axes])
    boxes=[font.getbbox(str(i)) for i in range(10)]
    top=min(b[1] for b in boxes);bottom=max(b[3] for b in boxes)
    width=max(b[2]-b[0] for b in boxes)+4;height=bottom-top+4
    all_data=[]
    for i,box in enumerate(boxes):
        canvas=Image.new('L',(width,height),0)
        ImageDraw.Draw(canvas).text(((width-(box[2]-box[0]))//2-box[0],2-top),str(i),font=font,fill=255)
        canvas=canvas.resize((WIDTH,HEIGHT),Image.Resampling.LANCZOS)
        levels=[min(15,(value*15+127)//255) for value in canvas.tobytes()]
        all_data.append(bytes(levels[at]|(levels[at+1]<<4) for at in range(0,len(levels),2)))
    lines=['/* SPDX-License-Identifier: OFL-1.1',
           ' * 从ChillDuanSans VF（Warren2060）生成的粗体数字；原OFL条款见sdcard/fonts/OFL.txt。',
           ' * Bold digit rasters derived from ChillDuanSans VF by Warren2060; see sdcard/fonts/OFL.txt.',
           ' * 生成工具：tools/generate_clock_digits.py；勿手改。 / Generated by tools/generate_clock_digits.py; do not edit.',
           ' * Source SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest(),' */','#pragma once','#include <stdint.h>',
           f'#define PS_CLOCK_MASK_W {WIDTH}',f'#define PS_CLOCK_MASK_H {HEIGHT}',
           f'static const uint8_t ps_clock_mask[10][{WIDTH*HEIGHT//2}]={{']
    for data in all_data:
        lines.append('    {')
        for at in range(0,len(data),24):lines.append('        '+','.join(f'0x{v:02x}' for v in data[at:at+24])+',')
        lines.append('    },')
    lines.append('};')
    return '\n'.join(lines)+'\n'


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    target=ROOT/'main/system/pico_clock_digits.h';text=generate()
    if args.check:assert target.read_text()==text,'regenerate pico_clock_digits.h'
    else:target.write_text(text)
    print(f'Clock digit masks: {WIDTH*HEIGHT*5:,} bytes, 16 gray levels; deterministic '+('check' if args.check else 'generation'))


if __name__=='__main__':
    main()
