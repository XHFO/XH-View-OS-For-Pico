#!/usr/bin/env python3
"""Build the lossless shared portal gzip include from its single UTF-8 HTML source."""
import argparse
import gzip
import hashlib
import io
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "components/read_pico_home_link/assets/home_link_portal.html"
TARGET = ROOT / "components/read_pico_home_link/home_link_portal_html_gzip.inc"


def generate() -> tuple[bytes, bytes, str]:
    raw = SOURCE.read_bytes()
    raw.decode("utf-8", errors="strict")
    stream = io.BytesIO()
    # Omit the source filename and timestamp, including when generated on another OS.
    with gzip.GzipFile(filename="", mode="wb", fileobj=stream, compresslevel=9, mtime=0) as archive:
        archive.write(raw)
    encoded = stream.getvalue()
    assert gzip.decompress(encoded) == raw
    assert encoded[:10] == bytes.fromhex("1f8b08000000000002ff")
    rows = ["    " + ", ".join(f"0x{byte:02x}" for byte in encoded[i:i + 12]) + ","
            for i in range(0, len(encoded), 12)]
    include = (
        "/* Generated by tools/build_home_portal_asset.py; do not edit.\n"
        " * SPDX-License-Identifier: Apache-2.0\n"
        f" * Source UTF-8 bytes: {len(raw)}; gzip bytes: {len(encoded)}; mtime: 0; filename: none.\n"
        f" * Source SHA-256: {hashlib.sha256(raw).hexdigest()}\n"
        " */\n"
        "static const unsigned char portal_html_gzip[] = {\n" + "\n".join(rows) + "\n};\n\n"
        "const unsigned char *rp_portal_html_gzip(size_t *encoded_bytes) {\n"
        "    if (encoded_bytes) *encoded_bytes = sizeof(portal_html_gzip);\n"
        "    return portal_html_gzip;\n"
        "}\n"
    )
    return raw, encoded, include


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the checked-in include is stale")
    args = parser.parse_args()
    raw, encoded, include = generate()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text() != include:
            raise SystemExit("Portal gzip is stale: run python3 tools/build_home_portal_asset.py")
    else:
        TARGET.write_text(include)
    print(f"PASS: portal HTML {len(raw)} UTF-8 bytes -> {len(encoded)} gzip bytes; "
          f"rodata saving {len(raw) + 1 - len(encoded)} bytes")


if __name__ == "__main__":
    main()
